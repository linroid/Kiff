  @Test
  fun everyFrozenPatchStillApplies() {
    for (vector in vectors) {
      val source = bytes(vector.source)
      val target = bytes(vector.target)
      val patch = bytes(vector.patch)
      val info = Kiff.info(patch)
      assertContentEquals(
        target,
        Kiff.patcher(info.patcher).applyPatch(source, patch),
        "frozen patch '${vector.name}' no longer restores its target"
      )
    }
  }

  @Test
  fun theFrozenPatchesCoverEveryEncoding() {
    // A vector suite that misses an encoding cannot notice it breaking. These four between them
    // exercise composite, delta, raw, text and columns.
    val seen = vectors.map { it.name }.toSet()
    for (required in listOf(
      "binary", "zipText", "zipAdded", "dexColumns",
      // The content codec changed; the older vectors above still carry the LZ77-only encoding, and
      // keeping both is how a reader that stopped decoding one of them would be noticed.
      "binaryPacked", "zipTextPacked", "dexColumnsPacked"
    )) {
      assertTrue(required in seen, "no vector covers $required")
    }
  }

  @Test
  fun theyAreStillVersionOne() {
    for (vector in vectors) {
      val info = Kiff.info(bytes(vector.patch))
      assertTrue(
        info.formatVersion == PatchFormat.VERSION,
        "vector '${vector.name}' is version ${info.formatVersion}, this build writes " +
          "${PatchFormat.VERSION} - a deliberate bump needs these regenerated"
      )
    }
  }

  private fun bytes(hex: String): ByteArray {
    val digits = hex.filter { it.isDigit() || it in 'a'..'f' }
    return ByteArray(digits.length / 2) {
      digits.substring(it * 2, it * 2 + 2).toInt(16).toByte()
    }
  }
