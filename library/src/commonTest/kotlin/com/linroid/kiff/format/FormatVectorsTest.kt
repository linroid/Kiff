  /** Keeps what a streamed restore hands over. */
  private class Collected : RestoreTarget {
    private val out = ByteWriter(64)

    override fun write(bytes: ByteArray, from: Int, to: Int) = out.writeBytes(bytes, from, to)

    fun bytes(): ByteArray = out.toByteArray()
  }

  /**
   * What the vectors hold, read by a walker of its own rather than by the reader under test, and
   * checking every region checksum against the bytes it covers on the way.
   */
  private class Coverage {
    val regions = mutableSetOf<Int>()
    val deltaOps = mutableSetOf<Int>()
    val textOps = mutableSetOf<Int>()
    val contentEncodings = mutableSetOf<Int>()
    val patchers = mutableSetOf<Int>()
    val flags = mutableSetOf<Int>()
    var negativeOffset = false
    var checksums = 0

    /** Where in the target the next region starts. */
    private var at = 0L

    fun walk(patch: ByteArray, target: ByteArray) {
      val reader = ByteReader(patch, MAGIC_BYTES)
      reader.readByte() // version
      patchers += reader.readByte()
      val flags = reader.readByte()
      this.flags += flags
      reader.readVarLong() // source size
      reader.readUInt32()
      reader.readVarLong() // target size
      reader.readUInt32()
      reader.readVarInt() // tree size
      reader.readVarInt() // content size
      contentEncodings += reader.readByte()
      reader.readVarInt() // stored size
      at = 0
      node(reader, target, flags and PatchFormat.FLAG_REGION_CHECKSUMS != 0, inColumns = false)
    }

    private fun node(
      tree: ByteReader,
      target: ByteArray,
      checksummed: Boolean,
      inColumns: Boolean
    ) {
      val length = tree.readVarLong()
      val encoding = tree.readByte()
      regions += encoding
      val leaf = encoding != RegionEncoding.COMPOSITE.code
      if (checksummed && leaf && !inColumns) {
        val expected = Crc32.compute(target, at.toInt(), (at + length).toInt())
        assertEquals(expected, tree.readUInt32(), "the region at $at is not the CRC of its bytes")
        checksums++
      }
      when (encoding) {
        RegionEncoding.COMPOSITE.code ->
          repeat(tree.readVarInt()) { node(tree, target, checksummed, inColumns) }

        RegionEncoding.DELTA.code -> {
          tree.readVarInt() // instruction bytes
          do {
            val op = (tree.readVarLong() and DeltaOp.MASK).toInt()
            deltaOps += op
            when (op) {
              DeltaOp.COPY, DeltaOp.DIFF -> if (tree.readSignedVarLong() < 0) negativeOffset = true
              DeltaOp.RUN -> tree.readByte()
            }
          } while (op != DeltaOp.END)
        }

        RegionEncoding.TEXT.code -> {
          tree.readVarLong() // source from
          tree.readVarLong() // source length
          tree.readVarInt() // edit bytes
          do {
            val op = tree.readByte()
            textOps += op
            if (op != TEXT_END) tree.readVarLong()
          } while (op != TEXT_END)
        }

        RegionEncoding.COLUMNS.code -> {
          tree.readVarLong() // source from
          tree.readVarLong() // source length
          repeat(tree.readByte()) { tree.readByte() }
          node(tree, target, checksummed, inColumns = true)
        }
      }
      // A node inside a columns region describes rearranged bytes; the columns node covers the
      // target bytes they turn back into.
      if (leaf && !inColumns) at += length
    }
  }

  private fun bytes(hex: String): ByteArray {
    val digits = hex.filter { it.isDigit() || it in 'a'..'f' }
    return ByteArray(digits.length / 2) {
      digits.substring(it * 2, it * 2 + 2).toInt(16).toByte()
    }
  }

  private companion object {
    const val MAGIC_BYTES = 4
    const val TEXT_END = 0
    const val TEXT_EQUAL = 1
    const val TEXT_DELETE = 2
    const val TEXT_INSERT = 3
  }
