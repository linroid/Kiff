/**
 * Patches frozen at the version of the format documented in FORMAT.md, with the inputs they were
 * built from, and the only claim that matters about them: they still apply.
 *
 * A format that lives only in code drifts from its own documentation, and the drift is silent.
 * Tinker's bundled bspatch is the cautionary tale - its header comments say the three streams are
 * bzip2 while the code has always read gzip, so anyone who trusted the comment and piped the
 * output to bspatch got nothing. Prose cannot fail; these can.
 *
 * Everything is hex rather than a fixture file so the suite runs on every target, and the inputs
 * are frozen alongside the patches rather than rebuilt, so changing a test builder cannot quietly
 * invalidate a vector. What the vectors cover is read off their bytes, not their names, so a
 * vector that stops holding what it was frozen for is noticed.
 *
 * **When one of these fails**, the question is not how to make it pass. It is whether the format
 * changed on purpose. Version 1 is released, so a change to what these bytes mean needs a new
 * version, and every later release still has to read these.
 */
