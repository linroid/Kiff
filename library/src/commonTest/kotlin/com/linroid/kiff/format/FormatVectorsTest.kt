  @Test
  fun everyFrozenPatchStillApplies() {
    for (vector in vectors) {
      val source = bytes(vector.source)
      val target = bytes(vector.target)
      val patch = bytes(vector.patch)
      val info = Kiff.info(patch)
      assertEquals(target.size.toLong(), info.targetSize, "'${vector.name}' declares another size")
      assertContentEquals(
        target,
        Kiff.applyPatch(source, patch),
        "frozen patch '${vector.name}' no longer restores its target"
      )
      val streamed = Collected()
      Kiff.applyPatch(ByteArraySource(source), patch, streamed)
      assertContentEquals(
        target,
        streamed.bytes(),
        "frozen patch '${vector.name}' no longer restores its target when streamed"
      )
    }
  }

  @Test
  fun theFrozenPatchesCoverTheWholeFormat() {
    // A vector suite that misses part of the format cannot notice it breaking.
    val seen = Coverage()
    for (vector in vectors) seen.walk(bytes(vector.patch), bytes(vector.target))
    assertEquals(RegionEncoding.entries.map { it.code }.toSet(), seen.regions, "region encodings")
    assertEquals(
      setOf(DeltaOp.END, DeltaOp.ADD, DeltaOp.COPY, DeltaOp.RUN, DeltaOp.DIFF),
      seen.deltaOps,
      "delta opcodes"
    )
    assertEquals(
      setOf(TEXT_END, TEXT_EQUAL, TEXT_DELETE, TEXT_INSERT),
      seen.textOps,
      "text opcodes"
    )
    assertEquals(
      setOf(PatchPayload.CONTENT_STORED, PatchPayload.CONTENT_LZ_HUFFMAN),
      seen.contentEncodings,
      "content encodings"
    )
    assertEquals(PatcherId.entries.map { it.code }.toSet(), seen.patchers, "patchers")
    assertEquals(setOf(0, PatchFormat.FLAG_REGION_CHECKSUMS), seen.flags, "flags")
    assertTrue(seen.negativeOffset, "no vector moves the source cursor backwards")
  }

  @Test
  fun regionChecksumsAreTheBigEndianCrcOfTheirBytes() {
    // The walk checks each one against the target range it covers, so this only has to make sure
    // there were some to check.
    val seen = Coverage()
    for (vector in vectors) seen.walk(bytes(vector.patch), bytes(vector.target))
    assertTrue(seen.checksums > 20, "only ${seen.checksums} region checksums were checked")
  }

